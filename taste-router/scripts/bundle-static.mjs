// Inline public/* into src/static.gen.js so the Worker serves the UI itself (no asset-upload step needed).
import { readFileSync, writeFileSync } from 'node:fs';
const files = { '/': ['index.html', 'text/html; charset=utf-8'], '/app.js': ['app.js', 'text/javascript; charset=utf-8'], '/style.css': ['style.css', 'text/css; charset=utf-8'] };
const out = Object.fromEntries(Object.entries(files).map(([route, [f, type]]) => [route, [type, readFileSync(new URL(`../public/${f}`, import.meta.url), 'utf8')]]));
out['/index.html'] = out['/'];
writeFileSync(new URL('../src/static.gen.js', import.meta.url), `// generated by scripts/bundle-static.mjs — do not edit\nexport default ${JSON.stringify(out)};\n`);
console.log('bundled', Object.keys(out).join(' '));
