// Regenerate every generated article page from its markdown source.
//
// The article class is read from the repository rather than typed into a list: a declared
// *.html page in docs/sitemap.xml that has a same-stem *.md. That is the same definition
// tools/article-registration.mjs audits, so a page that fails the registration guard can be
// fixed with one command - which is the difference between a guard people use and a guard
// people weaken.
//
// Being an article is NOT the same as being generated. The first version of this script used
// the sitemap-plus-.md rule alone and overwrote docs/prompt-enhancement.html, a hand-authored
// page, replacing 319 written lines with 164 generated ones. A generated page now says so in
// its own first lines, and anything without that sentence is left alone and reported.
import { spawnSync } from "node:child_process";
import { readFileSync, existsSync } from "node:fs";

export const MARKER = "generated by tools/render-evidence-page.mjs";

// Exported apart from the runner so the classification - the part that caused the damage -
// can be tested without rendering a copy of the site.
export function selectGenerated(names, readHead) {
  const generated = [];
  const handAuthored = [];
  for (const name of names) {
    // A page that is declared in the sitemap but not on disk yet is not hand-authored - it is a page
    // waiting to be rendered. The first version of this script read every declared page blindly and
    // crashed with ENOENT on the one that had just been registered, which is the exact moment the
    // command is most useful.
    let head = "";
    try {
      head = readHead(name);
    } catch (e) {
      if (e && e.code === "ENOENT") {
        generated.push(name);
        continue;
      }
      throw e;
    }
    if (head.slice(0, 400).includes(MARKER)) generated.push(name);
    else handAuthored.push(name);
  }
  return { generated, handAuthored };
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/").split("/").pop())) {
  const ROOT = "https://happy520ai.github.io/unified-ai-system/";
  const sitemap = readFileSync("docs/sitemap.xml", "utf8");
  const declared = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].split("/").pop());
  const withSource = declared.filter((name) => name.endsWith(".html") && existsSync("docs/" + name.replace(/\.html$/, ".md")));

  if (withSource.length === 0) {
    console.log("REFUSED: no article pages found in docs/sitemap.xml");
    process.exit(1);
  }

  const { generated, handAuthored } = selectGenerated(withSource, (name) => readFileSync("docs/" + name, "utf8"));

  let failed = 0;
  for (const name of generated) {
    const stem = name.replace(/\.html$/, "");
    const twin = existsSync("docs/" + stem + ".zh-CN.html") ? stem + ".zh-CN.html" : "";
    const args = ["tools/render-evidence-page.mjs", "--in", "docs/" + stem + ".md", "--out", "docs/" + name];
    if (twin) args.push("--twin", twin);
    const r = spawnSync(process.execPath, args, { encoding: "utf8" });
    if (r.status !== 0) {
      failed += 1;
      console.log("FAILED " + name + ": " + (r.stderr || r.stdout).trim().split("\n").slice(-1)[0]);
    } else {
      console.log("ok " + name + (twin ? " (hreflang twin)" : ""));
    }
  }
  for (const name of handAuthored) console.log("skipped (no generator marker, treated as hand-authored): " + name);
  console.log("regenerated=" + generated.length + " skipped=" + handAuthored.length + " failed=" + failed);
  process.exit(failed ? 1 : 0);
}
