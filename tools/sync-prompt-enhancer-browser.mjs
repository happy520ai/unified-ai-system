import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(
  repoRoot,
  "apps/ai-gateway-service/src/prompts/naturalLanguagePromptEnhancer.js",
);
const browserPath = resolve(repoRoot, "docs/prompt-enhancer.js");
const banner = "// Generated by pnpm sync:prompt-demo. Do not edit directly.\n";

writeFileSync(browserPath, `${banner}${readFileSync(sourcePath, "utf8")}`, "utf8");
console.log("Synced the browser prompt enhancer from the gateway runtime.");
