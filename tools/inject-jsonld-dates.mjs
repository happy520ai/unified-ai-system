// Set JSON-LD dates on a hand-authored page from git, touching nothing else in the file.
//
// Why this exists: the generated pages take their dates from git, but a hand-authored page carries a
// typed date that nobody updates. docs/prompt-enhancement.html advertised dateModified 2026-08-09 while
// the committed page had last changed on 2026-09-28 - a published freshness signal five weeks stale, and
// no check could see it because the audit only asked whether the keys existed.
//
// Deliberately narrow: it rewrites two string values inside the existing ld+json block and refuses
// everything else, because the generator must not take ownership of a hand-written body (a batch
// regeneration once replaced a 319-line hand-authored page with 164 generated lines).
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";

const MARKER = "<!-- generated by tools/render-evidence-page.mjs";

function utc(raw) {
  if (!raw) return null;
  const t = Date.parse(raw);
  return Number.isNaN(t) ? null : new Date(t).toISOString().replace(/\.\d{3}Z$/, "Z");
}

function gitDate(path, mode) {
  // "first" means the commit that added the file: --diff-filter=A with -1 takes the most recent addition,
  // and a file is added once. `git log --reverse -1` is not that - -1 still selects from the newest end.
  const args = ["log", "--format=%cI", "-1"];
  if (mode === "first") args.splice(1, 0, "--diff-filter=A");
  args.push("--", path);
  try {
    return execFileSync("git", args, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim().split("\n")[0] || "";
  } catch {
    return "";
  }
}

function main(argv) {
  const target = argv.find((a) => !a.startsWith("--"));
  if (!target) throw new Error("usage: node tools/inject-jsonld-dates.mjs docs/<page>.html [--dry]");
  const dry = argv.includes("--dry");
  const path = resolve(target);
  const before = readFileSync(path, "utf8");

  const fail = (why) => {
    console.log("REFUSED: " + why);
    process.exitCode = 2;
  };

  if (before.includes(MARKER)) return fail("this page is generator-owned; run pnpm docs:articles instead");
  if (Number(execFileSync("git", ["rev-list", "--count", "HEAD"], { encoding: "utf8" }).trim()) <= 1) {
    return fail("a one-commit clone has no history to date this page from");
  }

  const block = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/u.exec(before);
  if (!block) return fail("no JSON-LD block to date");
  let object;
  try {
    object = JSON.parse(block[1]);
  } catch (e) {
    return fail("the JSON-LD block is not parseable: " + e.message);
  }
  if (!object.datePublished || !object.dateModified) return fail("the block has no date fields to correct; add them by hand or generate the page");

  const name = target.split("/").pop();
  const stem = name.replace(/\.html$/, "");
  const htmlPath = "docs/" + name;
  const mdPath = "docs/" + stem + ".md";
  const published = utc(gitDate(htmlPath, "first"));
  if (!published) return fail("git could not report a first commit for " + htmlPath);
  const htmlLast = utc(gitDate(htmlPath, "last")) || "";
  let mdLast = "";
  try {
    readFileSync(mdPath, "utf8");
    mdLast = utc(gitDate(mdPath, "last")) || "";
  } catch {
    mdLast = ""; // a hand-authored page may have no markdown sibling at all
  }
  const modified = [htmlLast, mdLast].sort().pop();
  if (!modified) return fail("git could not report a last commit for " + htmlPath);
  if (published > modified) return fail("published " + published + " is after modified " + modified + "; the history is inconsistent");

  let after = before.replace(/("datePublished": *)"[^"]*"/u, "$1\"" + published + "\"");
  after = after.replace(/("dateModified": *)"[^"]*"/u, "$1\"" + modified + "\"");

  // Byte-level proof that only the two intended values moved.
  const beforeLines = before.split("\n");
  const afterLines = after.split("\n");
  if (beforeLines.length !== afterLines.length) return fail("line count changed (" + beforeLines.length + " -> " + afterLines.length + ")");
  const changed = [];
  for (let i = 0; i < beforeLines.length; i += 1) if (beforeLines[i] !== afterLines[i]) changed.push(i + 1);
  if (changed.length > 2) return fail("more than two lines changed: " + changed.join(","));
  for (const lineNo of changed) {
    if (!/datePublished|dateModified/.test(afterLines[lineNo - 1])) return fail("line " + lineNo + " changed without being a date line");
  }
  const reparsed = JSON.parse(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/u.exec(after)[1]);
  for (const key of Object.keys(object)) {
    if (key === "datePublished" || key === "dateModified") continue;
    if (JSON.stringify(reparsed[key]) !== JSON.stringify(object[key])) return fail("the block lost or changed " + key);
  }
  if (reparsed.datePublished !== published || reparsed.dateModified !== modified) return fail("the written dates are not the ones git reported");

  console.log("datePublished " + object.datePublished + " -> " + published);
  console.log("dateModified  " + object.dateModified + " -> " + modified);
  console.log("lines_changed " + (changed.join(",") || "none") + "  html_first_commit=" + gitDate(htmlPath, "first") + "  modified_from=max(" + (htmlLast || "n/a") + ", " + (mdLast || "no .md") + ")");
  if (dry) {
    console.log("DRY RUN: nothing written");
    return undefined;
  }
  if (changed.length === 0) {
    console.log("NO CHANGE: the dates already match git");
    return undefined;
  }
  writeFileSync(path, after, "utf8");
  console.log("WROTE " + target);
  return undefined;
}

try {
  main(process.argv.slice(2));
} catch (err) {
  console.log("FAILED: " + (err && err.message ? err.message : String(err)));
  process.exitCode = 2;
}
