// Set JSON-LD dates on a hand-authored page from git, touching nothing else in the file.
//
// Why this exists: the generated pages take their dates from git, but a hand-authored page carries a
// typed date that nobody updates. docs/prompt-enhancement.html advertised dateModified 2026-08-09 while
// the committed page had last changed on 2026-09-28 - a published freshness signal five weeks stale, and
// no check could see it because the audit only asked whether the keys existed.
//
// Deliberately narrow: it rewrites two string values inside the existing ld+json block and refuses
// everything else, because the generator must not take ownership of a hand-written body (a batch
// regeneration once replaced a 319-line hand-authored page with 164 generated lines).
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { lastContentChange } from "./git-content-date.mjs";

const MARKER = "<!-- generated by tools/render-evidence-page.mjs";

function utc(raw) {
  if (!raw) return null;
  const t = Date.parse(raw);
  return Number.isNaN(t) ? null : new Date(t).toISOString().replace(/\.\d{3}Z$/, "Z");
}

function firstCommitDate(path) {
  // The commit that added the file: --diff-filter=A with -1 takes the most recent addition, and a file is
  // added once. `git log --reverse -1` is not that - -1 still selects from the newest end. An addition is
  // always a content change, so this one does not need tools/git-content-date.mjs.
  const args = ["log", "--format=%cI", "-1", "--diff-filter=A"];
  args.push("--", path);
  try {
    return execFileSync("git", args, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim().split("\n")[0] || "";
  } catch {
    return "";
  }
}

function main(argv) {
  const target = argv.find((a) => !a.startsWith("--"));
  if (!target) throw new Error("usage: node tools/inject-jsonld-dates.mjs docs/<page>.html [--dry]");
  const dry = argv.includes("--dry");
  const check = argv.includes("--check");
  const path = resolve(target);
  const before = readFileSync(path, "utf8");

  const fail = (why) => {
    console.log("REFUSED: " + why);
    process.exitCode = 2;
  };

  if (before.includes(MARKER)) return fail("this page is generator-owned; run pnpm docs:articles instead");
  if (Number(execFileSync("git", ["rev-list", "--count", "HEAD"], { encoding: "utf8" }).trim()) <= 1) {
    return fail("a one-commit clone has no history to date this page from");
  }

  const block = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/u.exec(before);
  let object = null;
  if (block) {
    try {
      object = JSON.parse(block[1]);
    } catch (e) {
      return fail("the JSON-LD block is not parseable: " + e.message);
    }
  }
  const hasStructuredDates = Boolean(object && object.datePublished && object.dateModified);
  const hasMetaDates = /<meta property="article:(published|modified)_time" content="/u.test(before);
  if (!hasStructuredDates && !hasMetaDates) return fail("nothing to date: no JSON-LD dates and no article:*_time meta on this page");

  const name = target.split("/").pop();
  const stem = name.replace(/\.html$/, "");
  const htmlPath = "docs/" + name;
  const mdPath = "docs/" + stem + ".md";
  const published = utc(firstCommitDate(htmlPath));
  if (!published) return fail("git could not report a first commit for " + htmlPath);
  // Content, not contact. `git log -1` also answers with the commit that moved these very stamps, so a stamp
  // corrected on its own would be stale the moment it is committed - and on 2026-09-30 that made this check
  // unsatisfiable for 18 pages at once. The rule lives in one module because four tools date from git.
  const htmlRead = lastContentChange(htmlPath);
  const htmlLast = htmlRead.date || "";
  let mdLast = "";
  let mdError = "";
  try {
    readFileSync(mdPath, "utf8");
    const mdRead = lastContentChange(mdPath);
    mdLast = mdRead.date || "";
    mdError = mdRead.error || "";
  } catch {
    mdLast = ""; // a hand-authored page may have no markdown sibling at all
  }
  const modified = [htmlLast, mdLast].sort().pop();
  if (!modified) return fail("git reports no content change to date " + htmlPath + " by: " + [htmlRead.error, mdError].filter(Boolean).join(" | "));
  if (published > modified) return fail("published " + published + " is after modified " + modified + "; the history is inconsistent");

  let after = before;
  if (hasStructuredDates) {
    after = after.replace(/("datePublished": *)"[^"]*"/u, "$1\"" + published + "\"");
    after = after.replace(/("dateModified": *)"[^"]*"/u, "$1\"" + modified + "\"");
  }
  // The Open Graph timestamps say the same fact a third and fourth time, and hand-authored pages carried
  // values like 2026-09-25T00:00:00+00:00 - a midnight no commit happened at. Same reading, all four.
  after = after.replace(/(<meta property="article:published_time" content=")[^"]*"/gu, "$1" + published + "\"");
  after = after.replace(/(<meta property="article:modified_time" content=")[^"]*"/gu, "$1" + modified + "\"");

  // Byte-level proof that only the intended date values moved.
  const beforeLines = before.split("\n");
  const afterLines = after.split("\n");
  if (beforeLines.length !== afterLines.length) return fail("line count changed (" + beforeLines.length + " -> " + afterLines.length + ")");
  const changed = [];
  for (let i = 0; i < beforeLines.length; i += 1) if (beforeLines[i] !== afterLines[i]) changed.push(i + 1);
  if (changed.length > 4) return fail("more than four lines changed: " + changed.join(","));
  for (const lineNo of changed) {
    if (!/datePublished|dateModified|article:(published|modified)_time/u.test(afterLines[lineNo - 1])) {
      return fail("line " + lineNo + " changed without being a date line");
    }
  }
  if (hasStructuredDates) {
    const reparsed = JSON.parse(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/u.exec(after)[1]);
    for (const key of Object.keys(object)) {
      if (key === "datePublished" || key === "dateModified") continue;
      if (JSON.stringify(reparsed[key]) !== JSON.stringify(object[key])) return fail("the block lost or changed " + key);
    }
    if (reparsed.datePublished !== published || reparsed.dateModified !== modified) return fail("the written dates are not the ones git reported");
  }

  if (check) {
    // --check exists because the fixer was only ever run by hand. A page can carry four timestamps that
    // all restate the same fact, and every one of them can lag the commit that changed the prose - which
    // is what Google reads as freshness. Nothing else in the repository noticed: four deliberately stale
    // stamps on a published page still left `pnpm check:public` reporting zero issues.
    const stale = [];
    if (hasStructuredDates) {
      if (object.datePublished !== published) stale.push("datePublished " + object.datePublished + " should be " + published);
      if (object.dateModified !== modified) stale.push("dateModified " + object.dateModified + " should be " + modified);
    }
    const metaPublished = /<meta property="article:published_time" content="([^"]*)"/u.exec(before);
    const metaModified = /<meta property="article:modified_time" content="([^"]*)"/u.exec(before);
    if (metaPublished && metaPublished[1] !== published) stale.push("article:published_time " + metaPublished[1] + " should be " + published);
    if (metaModified && metaModified[1] !== modified) stale.push("article:modified_time " + metaModified[1] + " should be " + modified);
    if (stale.length === 0) {
      console.log("IN DATE " + target + " published=" + published + " modified=" + modified);
      return undefined;
    }
    console.log("STALE " + target + " " + stale.join(" | ") + "  (run: node tools/inject-jsonld-dates.mjs " + target + ")");
    process.exitCode = 4;
    return undefined;
  }

  console.log("datePublished " + (object && object.datePublished ? object.datePublished : "(no structured value)") + " -> " + published);
  console.log("dateModified  " + (object && object.dateModified ? object.dateModified : "(no structured value)") + " -> " + modified);
  console.log("lines_changed " + (changed.join(",") || "none") + "  html_first_commit=" + firstCommitDate(htmlPath) + "  modified_from=max(" + (htmlLast || "n/a") + ", " + (mdLast || "no .md") + ")  date_only_commits_stepped_over=" + htmlRead.skipped);
  if (dry) {
    console.log("DRY RUN: nothing written");
    return undefined;
  }
  if (changed.length === 0) {
    console.log("NO CHANGE: the dates already match git");
    return undefined;
  }
  writeFileSync(path, after, "utf8");
  console.log("WROTE " + target);
  return undefined;
}

try {
  main(process.argv.slice(2));
} catch (err) {
  console.log("FAILED: " + (err && err.message ? err.message : String(err)));
  process.exitCode = 2;
}
